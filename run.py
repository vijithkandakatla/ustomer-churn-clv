"""Churn prediction + survival analysis + CLV-based retention targeting."""
import argparse
from datetime import date
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd

from src.churn_model import cross_validate
from src.data import load, model_matrix
from src.readme_utils import df_to_markdown, update_readme
from src.survival_clv import expected_clv, fit_cox, kaplan_meier_by, retention_segments

RESULTS = Path(__file__).resolve().parent / "results"


def lift_curve(y, oof, path):
    fig, ax = plt.subplots(figsize=(5.5, 4))
    share = np.linspace(0.01, 1, 100)
    for name, p in oof.items():
        order = np.argsort(-p); ys = np.asarray(y)[order]
        cap = [ys[: int(np.ceil(s * len(ys)))].sum() / ys.sum() for s in share]
        ax.plot(share * 100, np.array(cap) * 100, label=name)
    ax.plot([0, 100], [0, 100], "k--", lw=1, label="random")
    ax.set(xlabel="% of customers contacted (highest risk first)", ylabel="% of churners reached",
           title="Cumulative gains (out-of-fold)")
    ax.legend(); ax.grid(alpha=0.3); fig.tight_layout(); fig.savefig(path, dpi=150); plt.close(fig)


def main(a):
    RESULTS.mkdir(exist_ok=True)
    df = load(a.data)
    y = df["churn"]
    X = model_matrix(df)
    print(f"{len(df):,} customers, churn rate {y.mean():.1%}")

    # 1. classification
    cls, oof, _ = cross_validate(X, y)
    lift_curve(y, oof, RESULTS / "cumulative_gains.png")
    cls.to_csv(RESULTS / "churn_model_cv.csv", index=False)

    # 2. survival
    fig, ax = plt.subplots(figsize=(6, 4))
    _, p_contract = kaplan_meier_by(df[df["tenure"] > 0], "Contract", ax=ax)
    ax.set(title="Kaplan-Meier: customer survival by contract", xlabel="Tenure (months)", ylabel="P(still a customer)")
    fig.tight_layout(); fig.savefig(RESULTS / "km_by_contract.png", dpi=150); plt.close(fig)
    cph, Xc = fit_cox(df)
    hr = cph.summary[["exp(coef)", "p"]].rename(columns={"exp(coef)": "Hazard ratio", "p": "p-value"})
    hr = hr.reindex(hr["Hazard ratio"].sub(1).abs().sort_values(ascending=False).index).head(8)
    hr.to_csv(RESULTS / "cox_hazard_ratios_top.csv")
    cph.summary.to_csv(RESULTS / "cox_full_summary.csv")

    # 3. CLV + segments
    clv = expected_clv(cph, Xc, df, margin=a.margin)
    seg, clv = retention_segments(clv)
    clv.sort_values("clv_24m", ascending=False).to_csv(RESULTS / "customer_clv_scores.csv", index=False)
    target = clv[clv["segment"].str.startswith("1.")].sort_values("clv_24m", ascending=False)
    target.head(200).to_csv(RESULTS / "retention_target_list.csv", index=False)

    best = cls.sort_values("ROC-AUC", ascending=False).iloc[0]
    hr_md = hr.reset_index().rename(columns={"covariate": "Feature", "index": "Feature"})
    hr_md["Hazard ratio"] = hr_md["Hazard ratio"].map(lambda v: f"{v:.2f}")
    hr_md["p-value"] = hr_md["p-value"].map(lambda v: "<0.001" if v < 0.001 else f"{v:.3f}")
    cls_md = cls.copy()
    for c in ("ROC-AUC", "PR-AUC", "F1 (thr 0.5)"):
        cls_md[c] = cls_md[c].map(lambda v: f"{v:.3f}")
    cls_md["Top-10% lift"] = cls_md["Top-10% lift"].map(lambda v: f"{v:.1f}×")
    cls_md["Churners caught in top 10%"] = cls_md["Churners caught in top 10%"].map(lambda v: f"{v:.0%}")
    seg_md = seg.copy()
    seg_md["avg_p_churn_12m"] = seg_md["avg_p_churn_12m"].map(lambda v: f"{v:.0%}")
    for c in ("avg_clv", "total_clv", "clv_at_risk_12m"):
        seg_md[c] = seg_md[c].map(lambda v: f"${v:,.0f}")
    seg_md.columns = ["Segment", "Customers", "Avg 12-m churn prob.", "Avg CLV (24 m)", "Total CLV", "CLV at risk (12 m)"]
    share_at_risk = seg.loc[seg.segment.str.startswith("1."), "clv_at_risk_12m"].sum() / seg["clv_at_risk_12m"].sum()
    seg1_share = seg.loc[seg.segment.str.startswith("1."), "customers"].sum() / seg["customers"].sum()

    md = f"""_Generated by `python run.py` on {date.today():%d %b %Y}._  Dataset: {len(df):,} customers, churn rate {y.mean():.1%}.

### 1. Churn prediction (5-fold stratified CV, out-of-fold)

{df_to_markdown(cls_md)}

Best model: **{best.Model}**. Contacting the riskiest 10% of customers reaches **{best['Churners caught in top 10%']:.0%} of all churners** ({best['Top-10% lift']:.1f}× better than random).

![Cumulative gains](results/cumulative_gains.png)

### 2. Survival analysis – *when* do customers leave?

Log-rank test across contract types: p {"< 0.001" if p_contract < 0.001 else f"= {p_contract:.3f}"}. Cox proportional-hazards model concordance: **{cph.concordance_index_:.3f}**.

Strongest effects (hazard ratio > 1 = churns sooner, < 1 = stays longer):

{df_to_markdown(hr_md)}

![Kaplan-Meier by contract](results/km_by_contract.png)

### 3. Customer lifetime value & retention targeting

24-month discounted CLV per active customer from the Cox survival curves (assumed {a.margin:.0%} margin, 10% annual discount rate):

{df_to_markdown(seg_md)}

The **"high value, high risk" segment is {seg1_share:.0%} of customers but holds {share_at_risk:.0%} of the CLV at risk** over the next 12 months. Its top 200 customers are exported to `results/retention_target_list.csv`.
"""
    (RESULTS / "results.md").write_text(md, encoding="utf-8")
    if not a.no_readme:
        update_readme(md)
    print(md)


if __name__ == "__main__":
    p = argparse.ArgumentParser()
    p.add_argument("--data", type=Path, default=None)
    p.add_argument("--margin", type=float, default=0.30)
    p.add_argument("--no-readme", action="store_true")
    main(p.parse_args())
